CREATE TABLE IF NOT EXISTS `user` (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone VARCHAR(20), email VARCHAR(100), password VARCHAR(255) NOT NULL,
  nickname VARCHAR(50), avatar VARCHAR(500), points INT DEFAULT 0,
  level SMALLINT DEFAULT 0, status INT DEFAULT 0, register_source VARCHAR(20),
  last_login_time TIMESTAMP, last_login_ip VARCHAR(45), create_time TIMESTAMP,
  update_time TIMESTAMP, deleted BOOLEAN DEFAULT FALSE, gender INT, birth_date DATE
);
CREATE TABLE IF NOT EXISTS role (
  id INT PRIMARY KEY, role_name VARCHAR(20) NOT NULL, permission VARCHAR(500)
);
CREATE TABLE IF NOT EXISTS user_role (
  user_id BIGINT NOT NULL, role_id INT NOT NULL, PRIMARY KEY (user_id, role_id)
);
CREATE TABLE IF NOT EXISTS traveler (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL,
  name VARCHAR(50) NOT NULL, id_card VARCHAR(20) NOT NULL, phone VARCHAR(20),
  id_type INT DEFAULT 0, create_time TIMESTAMP
);
CREATE TABLE IF NOT EXISTS points_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL,
  type INT NOT NULL, amount INT NOT NULL, source VARCHAR(50), order_id BIGINT,
  create_time TIMESTAMP
);
CREATE TABLE IF NOT EXISTS user_login_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL,
  login_time TIMESTAMP, login_ip VARCHAR(45), device VARCHAR(100)
);
CREATE TABLE IF NOT EXISTS auth_verification_code (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, target VARCHAR(128) NOT NULL,
  channel VARCHAR(20) NOT NULL, code VARCHAR(20) NOT NULL, expire_time TIMESTAMP NOT NULL,
  consumed_time TIMESTAMP, send_count INT DEFAULT 0, create_time TIMESTAMP, update_time TIMESTAMP
);
CREATE TABLE IF NOT EXISTS admin_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, admin_id BIGINT NOT NULL,
  operation VARCHAR(50) NOT NULL, params VARCHAR(2000), result VARCHAR(20),
  ip VARCHAR(45), create_time TIMESTAMP
);
MERGE INTO role (id, role_name, permission) KEY (id)
    VALUES (1, 'ADMIN', '*'), (2, 'USER', '');
